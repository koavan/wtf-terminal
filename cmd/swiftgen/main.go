// Command swiftgen writes the native macOS app's Swift view of the Go
// backend: a Codable struct for every type the services' methods take or
// return, and a typed async function per method. Run it after changing a
// service's methods or types:
//
//	go run ./cmd/swiftgen
//
// It writes macos/Sources/WtfCore/Generated/Models.swift and
// macos/Sources/Wtf/Generated/Services.swift.
package main

import (
	"bytes"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"
	"time"
	"unicode"

	"github.com/dayanraj/wtf/internal/backend"
)

// Methods that are lifecycle hooks, not calls.
var skip = map[string]bool{"ServiceStartup": true, "ServiceShutdown": true, "ServeHTTP": true}

var (
	errorType = reflect.TypeFor[error]()
	timeType  = reflect.TypeFor[time.Time]()
	ctxName   = "context.Context"
)

type gen struct {
	// Struct types to emit, by Swift name.
	structs map[string]reflect.Type
	order   []string
}

// pkg is the last element of a type's package path ("sshhosts").
func pkg(t reflect.Type) string { return filepath.Base(t.PkgPath()) }

// swiftName qualifies a Go struct by its package: Go.sshhosts.Host.
func (g *gen) swiftName(t reflect.Type) string {
	name := "Go." + pkg(t) + "." + t.Name()
	if _, ok := g.structs[name]; !ok {
		g.structs[name] = t
		g.order = append(g.order, name)
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			if f.IsExported() {
				g.swiftType(f.Type)
			}
		}
	}
	return name
}

// swiftType maps a Go type to Swift, registering structs on the way.
func (g *gen) swiftType(t reflect.Type) string {
	if t == timeType {
		return "String"
	}
	switch t.Kind() {
	case reflect.String:
		return "String"
	case reflect.Bool:
		return "Bool"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return "Int"
	case reflect.Float32, reflect.Float64:
		return "Double"
	case reflect.Pointer:
		return g.swiftType(t.Elem()) + "?"
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 && t.Kind() == reflect.Slice {
			if t.Name() == "RawMessage" {
				return "JSONValue"
			}
			return "String" // []byte is base64 in JSON
		}
		return "[" + strings.TrimSuffix(g.swiftType(t.Elem()), "?") + "]"
	case reflect.Map:
		return "[String: " + strings.TrimSuffix(g.swiftType(t.Elem()), "?") + "]"
	case reflect.Interface:
		return "JSONValue"
	case reflect.Struct:
		return g.swiftName(t)
	}
	log.Fatalf("unsupported type %v", t)
	return ""
}

// defaultValue is what a field decodes to when JSON leaves it out or null.
func defaultValue(swift string) string {
	switch {
	case strings.HasSuffix(swift, "?"):
		return "nil"
	case swift == "String":
		return `""`
	case swift == "Bool":
		return "false"
	case swift == "Int", swift == "Double":
		return "0"
	case swift == "JSONValue":
		return ".null"
	case strings.HasPrefix(swift, "[") && strings.Contains(swift, ":"):
		return "[:]"
	case strings.HasPrefix(swift, "["):
		return "[]"
	}
	return swift + "()"
}

type field struct{ json, swift, typ string }

// fields lists a struct's JSON fields, flattening embedded structs.
func (g *gen) fields(t reflect.Type) []field {
	var out []field
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if !f.IsExported() {
			continue
		}
		tag := f.Tag.Get("json")
		name, _, _ := strings.Cut(tag, ",")
		if name == "-" {
			continue
		}
		if f.Anonymous && name == "" && f.Type.Kind() == reflect.Struct {
			out = append(out, g.fields(f.Type)...)
			continue
		}
		if name == "" {
			name = f.Name
		}
		out = append(out, field{json: name, swift: swiftIdent(name), typ: g.swiftType(f.Type)})
	}
	return out
}

var reserved = map[string]bool{"default": true, "in": true, "is": true, "as": true, "case": true, "class": true, "func": true,
	"import": true, "init": true, "let": true, "var": true, "return": true, "self": true, "static": true, "struct": true,
	"switch": true, "where": true, "while": true, "repeat": true, "protocol": true, "operator": true, "extension": true,
	"enum": true, "internal": true, "public": true, "private": true, "Type": true, "subscript": true, "throw": true}

func swiftIdent(json string) string {
	var b strings.Builder
	upper := false
	for i, r := range json {
		switch {
		case r == '-' || r == '_' || r == ' ':
			upper = i > 0
		case upper:
			b.WriteRune(unicode.ToUpper(r))
			upper = false
		default:
			b.WriteRune(r)
		}
	}
	s := b.String()
	if s == "" || unicode.IsDigit(rune(s[0])) {
		s = "_" + s
	}
	if reserved[s] {
		return "`" + s + "`"
	}
	return s
}

func (g *gen) models() []byte {
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Generated by cmd/swiftgen from the Go services' types. Do not edit:")
	fmt.Fprintln(&b, "// change the Go types and run `go run ./cmd/swiftgen`.")
	fmt.Fprintln(&b, "//")
	fmt.Fprintln(&b, "// Decoding is lenient, like the Svelte build's: a field Go leaves out or")
	fmt.Fprintln(&b, "// sends as null gets its zero value.")
	fmt.Fprintln(&b, "// swiftlint:disable all")
	fmt.Fprintln(&b, "import Foundation")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "public enum Go {}")
	pkgs := map[string]bool{}
	for _, n := range g.order {
		pkgs[pkg(g.structs[n])] = true
	}
	var names []string
	for p := range pkgs {
		names = append(names, p)
	}
	sort.Strings(names)
	for _, p := range names {
		fmt.Fprintf(&b, "extension Go { public enum %s {} }\n", p)
	}
	sorted := append([]string(nil), g.order...)
	sort.Strings(sorted)
	for _, n := range sorted {
		t := g.structs[n]
		fs := g.fields(t)
		fmt.Fprintf(&b, "\nextension Go.%s {\n", pkg(t))
		fmt.Fprintf(&b, "    /// %s.%s\n", pkg(t), t.Name())
		fmt.Fprintf(&b, "    public struct %s: Codable, Equatable, Sendable {\n", t.Name())
		for _, f := range fs {
			fmt.Fprintf(&b, "        public var %s: %s\n", f.swift, f.typ)
		}
		// Memberwise init with defaults, for building arguments.
		var params []string
		for _, f := range fs {
			params = append(params, fmt.Sprintf("%s: %s = %s", f.swift, f.typ, defaultValue(f.typ)))
		}
		fmt.Fprintf(&b, "\n        public init(%s) {\n", strings.Join(params, ", "))
		for _, f := range fs {
			fmt.Fprintf(&b, "            self.%s = %s\n", f.swift, f.swift)
		}
		fmt.Fprintln(&b, "        }")
		if len(fs) > 0 {
			fmt.Fprintln(&b, "\n        enum CodingKeys: String, CodingKey {")
			for _, f := range fs {
				fmt.Fprintf(&b, "            case %s = %q\n", f.swift, f.json)
			}
			fmt.Fprintln(&b, "        }")
			fmt.Fprintln(&b, "\n        public init(from decoder: Decoder) throws {")
			fmt.Fprintln(&b, "            let c = try decoder.container(keyedBy: CodingKeys.self)")
			for _, f := range fs {
				base := strings.TrimSuffix(f.typ, "?")
				fmt.Fprintf(&b, "            self.%s = (try? c.decodeIfPresent(%s.self, forKey: .%s)) ?? %s\n",
					f.swift, base, f.swift, defaultValue(f.typ))
			}
			fmt.Fprintln(&b, "        }")
		} else {
			fmt.Fprintln(&b, "\n        public init(from decoder: Decoder) throws {}")
			fmt.Fprintln(&b, "        public func encode(to encoder: Encoder) throws {}")
		}
		fmt.Fprintln(&b, "    }")
		fmt.Fprintln(&b, "}")
	}
	return b.Bytes()
}

type method struct {
	service, name string
	params        []string // Swift types
	result        string   // "" for none
}

func (g *gen) services() ([]byte, int) {
	var methods []method
	bt := reflect.TypeFor[backend.Backend]()
	// Service names in the order the backend lists them, from its struct fields.
	names := map[reflect.Type]string{}
	for _, n := range serviceNames() {
		names[n.typ] = n.name
	}
	for i := 0; i < bt.NumField(); i++ {
		f := bt.Field(i)
		svc, ok := names[f.Type]
		if !ok {
			continue
		}
		for j := 0; j < f.Type.NumMethod(); j++ {
			m := f.Type.Method(j)
			if skip[m.Name] {
				continue
			}
			mt := m.Type
			var params []string
			for k := 1; k < mt.NumIn(); k++ {
				params = append(params, strings.TrimSuffix(g.swiftType(mt.In(k)), "?")+optional(mt.In(k)))
			}
			var outs []reflect.Type
			for k := 0; k < mt.NumOut(); k++ {
				if mt.Out(k) != errorType {
					outs = append(outs, mt.Out(k))
				}
			}
			result := ""
			switch len(outs) {
			case 0:
			case 1:
				result = g.swiftType(outs[0])
			default:
				result = "[JSONValue]"
			}
			methods = append(methods, method{svc, m.Name, params, result})
		}
	}
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Generated by cmd/swiftgen from the Go services' methods. Do not edit:")
	fmt.Fprintln(&b, "// change the Go methods and run `go run ./cmd/swiftgen`.")
	fmt.Fprintln(&b, "// swiftlint:disable all")
	fmt.Fprintln(&b, "import Foundation")
	fmt.Fprintln(&b, "import WtfCore")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "/// Typed calls to the backend services (Backend.call underneath).")
	fmt.Fprintln(&b, "enum Services {")
	last := ""
	for _, m := range methods {
		if m.service != last {
			if last != "" {
				fmt.Fprintln(&b, "    }")
				fmt.Fprintln(&b)
			}
			fmt.Fprintf(&b, "    enum %s {\n", m.service)
			last = m.service
		}
		var ps, args []string
		for i, p := range m.params {
			ps = append(ps, fmt.Sprintf("_ a%d: %s", i, p))
			args = append(args, fmt.Sprintf("a%d", i))
		}
		argList := "[" + strings.Join(args, ", ") + "]"
		if len(args) == 0 {
			argList = "[]"
		}
		if m.result == "" {
			fmt.Fprintf(&b, "        static func %s(%s) async throws { try await Backend.run(%q, %q, %s) }\n",
				m.name, strings.Join(ps, ", "), m.service, m.name, argList)
		} else {
			fmt.Fprintf(&b, "        static func %s(%s) async throws -> %s { try await Backend.call(%q, %q, %s, as: %s.self) }\n",
				m.name, strings.Join(ps, ", "), m.result, m.service, m.name, argList, strings.TrimSuffix(m.result, "?"))
		}
	}
	if last != "" {
		fmt.Fprintln(&b, "    }")
	}
	fmt.Fprintln(&b, "}")
	return b.Bytes(), len(methods)
}

func optional(t reflect.Type) string {
	if t.Kind() == reflect.Pointer {
		return "?"
	}
	return ""
}

type svcName struct {
	name string
	typ  reflect.Type
}

// serviceNames maps each service's Go type to the name the native bridge
// calls it by (backend.Services).
func serviceNames() []svcName {
	var out []svcName
	b := reflect.ValueOf(&backend.Backend{}).Elem()
	bt := b.Type()
	for i := 0; i < bt.NumField(); i++ {
		f := bt.Field(i)
		if f.Type.Kind() == reflect.Pointer && f.Type.Elem().Name() == "Service" {
			out = append(out, svcName{pkg(f.Type.Elem()), f.Type})
		}
	}
	return out
}

func main() {
	root, err := os.Getwd()
	if err != nil {
		log.Fatal(err)
	}
	g := &gen{structs: map[string]reflect.Type{}}
	svc, n := g.services()
	models := g.models()
	write := func(rel string, data []byte) {
		p := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile(p, data, 0o644); err != nil {
			log.Fatal(err)
		}
	}
	write("macos/Sources/WtfCore/Generated/Models.swift", models)
	write("macos/Sources/Wtf/Generated/Services.swift", svc)
	fmt.Printf("%d types, %d methods\n", len(g.structs), n)
}
